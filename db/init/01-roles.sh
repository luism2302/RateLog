#!/usr/bin/env bash
set -euo pipefail

: "${RATELOG_OWNER_PASSWORD:?missing RATELOG_OWNER_PASSWORD}"
: "${RATELOG_APP_PASSWORD:?missing RATELOG_APP_PASSWORD}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'EOSQL'
\getenv owner_password RATELOG_OWNER_PASSWORD
\getenv app_password RATELOG_APP_PASSWORD
\getenv db_name POSTGRES_DB

CREATE ROLE ratelog_owner LOGIN PASSWORD :'owner_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE ratelog_app LOGIN PASSWORD :'app_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

REVOKE ALL ON DATABASE :"db_name" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"db_name" TO ratelog_owner, ratelog_app;

ALTER SCHEMA public OWNER TO ratelog_owner;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO ratelog_app;

ALTER DEFAULT PRIVILEGES FOR ROLE ratelog_owner IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ratelog_app;
ALTER DEFAULT PRIVILEGES FOR ROLE ratelog_owner IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO ratelog_app;

ALTER DEFAULT PRIVILEGES FOR ROLE ratelog_owner
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
EOSQL
